import React from 'react';
import {Composition, Still} from 'remotion';
import {ArticleCover} from './ArticleCover';
import {EffortVideo} from './EffortVideo';
import {FPS, H, TL, W} from './lib';
import {QayyimReel} from './qayyim/QayyimReel';
import {QH, QW, ReelTimeline} from './qayyim/theme';
import r00 from '../reels/qayyim/00-who.json';
import r01 from '../reels/qayyim/01-fawaid.json';
import r02 from '../reels/qayyim/02-madarij.json';
import r03 from '../reels/qayyim/03-ighathah.json';
import r04 from '../reels/qayyim/04-wabil.json';
import r05 from '../reels/qayyim/05-jawab.json';
import r06 from '../reels/qayyim/06-miftah.json';
import r07 from '../reels/qayyim/07-uddah.json';
import r08 from '../reels/qayyim/08-zad.json';

// Ibn al-Qayyim reel series: one timeline per reel, generated by scripts/qayyim-timeline.mjs.
const QAYYIM: {id: string; tl: ReelTimeline}[] = [
  {id: '00-who', tl: r00},
  {id: '01-fawaid', tl: r01},
  {id: '02-madarij', tl: r02},
  {id: '03-ighathah', tl: r03},
  {id: '04-wabil', tl: r04},
  {id: '05-jawab', tl: r05},
  {id: '06-miftah', tl: r06},
  {id: '07-uddah', tl: r07},
  {id: '08-zad', tl: r08},
];

export const Root: React.FC = () => (
  <>
    <Composition
      id="EffortVideo"
      component={EffortVideo}
      durationInFrames={Math.round(TL.duration * FPS)}
      fps={FPS}
      width={W}
      height={H}
    />
    {QAYYIM.map(({id, tl}) => (
      <Composition
        key={id}
        id={`Qayyim-${id}`}
        component={QayyimReel}
        defaultProps={{tl}}
        durationInFrames={Math.round(tl.duration * tl.fps)}
        fps={tl.fps}
        width={QW}
        height={QH}
      />
    ))}
    <Still id="ArticleCover" component={ArticleCover} width={2000} height={800} />
  </>
);
